  for select using (true);

drop policy if exists "perfis_criar_proprio" on public.perfis_clube;
create policy "perfis_criar_proprio" on public.perfis_clube
  for insert with check (
    id = auth.uid()
    and pode_publicar_resenha = false
  );

drop policy if exists "perfis_atualizar_proprio" on public.perfis_clube;
create policy "perfis_atualizar_proprio" on public.perfis_clube
  for update using (id = auth.uid())
  with check (
    id = auth.uid()
    and pode_publicar_resenha = public.clube_permissao_resenha(auth.uid())
  );

drop policy if exists "perfis_admin_total" on public.perfis_clube;
create policy "perfis_admin_total" on public.perfis_clube
  for all using (public.clube_e_admin())
  with check (public.clube_e_admin());

