create or replace function public.clube_progresso_compartilhado_visivel(p_id_publico uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.progresso_leitura_compartilhado compartilhado
    join public.encontros encontro
      on encontro.id = compartilhado.encontro_id
    join lateral (
      select coalesce(sum(progresso.paginas_lidas), 0) as total_paginas
      from public.progresso_leitura progresso
      where progresso.usuario_id = compartilhado.usuario_id
        and progresso.encontro_id = compartilhado.encontro_id
        and progresso.data_leitura <= current_date
    ) total on true
    where compartilhado.id_publico = p_id_publico
      and encontro.status = 'atual'
      and coalesce(encontro.tipo_postagem, 'clube') = 'clube'
      and total.total_paginas > 0
  );
$$;

