-- Executar no SQL Editor do Supabase.
-- Preserva tabelas existentes e habilita segurança por proprietário e Admin Master.

create or replace function public.clube_e_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) =
         'lohanpereiradosreis@gmail.com';
$$;

create table if not exists public.perfis_clube (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '',
  nome text not null default 'Leitor(a)',
  foto_url text not null default '',
  pode_publicar_resenha boolean not null default false,
  criado_em timestamptz not null default now()
);

create or replace function public.clube_permissao_resenha(usuario uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select pode_publicar_resenha from public.perfis_clube where id = usuario),
    false
  );
$$;

create table if not exists public.encontros (
  id bigint generated by default as identity primary key,
  titulo text not null,
  autor text not null,
  capa text not null default '',
  genero text not null default 'Outro',
  status text not null default 'atual',
  data_encontro date,
  horario_local text not null default '',
  paginas_totais integer not null default 0,
  pagina_meta integer not null default 0,
  meta_texto text not null default '',
  nota numeric(3,1),
  bio_autor text not null default '',
  discussao text not null default '',
  fotos jsonb not null default '[]'::jsonb,
  tipo_postagem text not null default 'clube',
  autor_postagem_id uuid references auth.users(id) on delete set null,
  autor_postagem_nome text not null default '',
  criado_em timestamptz not null default now()
);

create table if not exists public.guia_clube (
  id integer primary key,
  titulo text not null,
  conteudo text not null,
  atualizado_em timestamptz not null default now()
);

create table if not exists public.avaliacoes_livro (
  encontro_id bigint not null references public.encontros(id) on delete cascade,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  nota numeric(3,1) not null,
  atualizado_em timestamptz not null default now(),
  primary key (encontro_id, usuario_id),
  constraint avaliacao_nota_valida check (nota >= 0 and nota <= 5)
);

create table if not exists public.comentarios_livro (
  id bigint generated by default as identity primary key,
  encontro_id bigint not null references public.encontros(id) on delete cascade,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  texto text not null,
  criado_em timestamptz not null default now()
);

create table if not exists public.indicacoes_livro (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  titulo text not null,
  autor text not null,
  genero text not null default '',
  motivo text not null default '',
  criado_em timestamptz not null default now()
);

create table if not exists public.votos_indicacao (
  indicacao_id bigint not null references public.indicacoes_livro(id) on delete cascade,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  criado_em timestamptz not null default now(),
  primary key (indicacao_id, usuario_id)
);

create table if not exists public.progresso_leitura (
  usuario_id uuid not null references auth.users(id) on delete cascade,
  encontro_id bigint not null references public.encontros(id) on delete cascade,
  data_leitura date not null,
  paginas_lidas integer not null default 0,
  atualizado_em timestamptz not null default now(),
  primary key (usuario_id, encontro_id, data_leitura),
  constraint progresso_paginas_validas
    check (paginas_lidas >= 0)
);

alter table public.encontros add column if not exists paginas_totais integer not null default 0;
alter table public.encontros add column if not exists pagina_meta integer not null default 0;
alter table public.encontros add column if not exists nota numeric(3,1);
alter table public.encontros add column if not exists fotos jsonb not null default '[]'::jsonb;
alter table public.encontros add column if not exists tipo_postagem text not null default 'clube';
alter table public.encontros add column if not exists autor_postagem_id uuid references auth.users(id) on delete set null;
alter table public.encontros add column if not exists autor_postagem_nome text not null default '';

alter table public.perfis_clube enable row level security;
alter table public.encontros enable row level security;
alter table public.guia_clube enable row level security;
alter table public.avaliacoes_livro enable row level security;
alter table public.comentarios_livro enable row level security;
alter table public.indicacoes_livro enable row level security;
alter table public.votos_indicacao enable row level security;
alter table public.progresso_leitura enable row level security;

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'encontro_paginas_validas') then
    alter table public.encontros add constraint encontro_paginas_validas
      check (paginas_totais >= 0 and pagina_meta >= 0 and pagina_meta <= paginas_totais);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'encontro_nota_valida') then
    alter table public.encontros add constraint encontro_nota_valida
      check (nota is null or (nota >= 0 and nota <= 5));
  end if;
end $$;

drop policy if exists "perfis_leitura_publica" on public.perfis_clube;
