create or replace function public.clube_metricas_grupo(p_encontro_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  resultado jsonb;
  progresso_coletivo jsonb;
begin
  if not exists (
    select 1
    from public.encontros e
    where e.id = p_encontro_id
      and e.status = 'atual'
      and coalesce(e.tipo_postagem, 'clube') = 'clube'
  ) then
    return jsonb_build_object(
      'total_paginas', 0,
      'paginas_hoje', 0,
      'paginas_semana', 0,
      'paginas_mes', 0,
      'leitores_ativos', 0,
      'participantes_com_edicao', 0,
      'participantes_com_progresso', 0,
      'paginas_medias_por_membro', 0,
      'progresso_medio_percentual', 0,
      'progresso_por_edicao', '[]'::jsonb,
      'atividade_anonima', '[]'::jsonb
    );
  end if;

  select jsonb_build_object(
    'total_paginas', coalesce(sum(p.paginas_lidas), 0),
    'paginas_hoje', coalesce(sum(p.paginas_lidas)
      filter (where p.data_leitura = current_date), 0),
    'paginas_semana', coalesce(sum(p.paginas_lidas)
      filter (where p.data_leitura >= date_trunc('week', current_date)::date), 0),
    'paginas_mes', coalesce(sum(p.paginas_lidas)
      filter (where p.data_leitura >= date_trunc('month', current_date)::date), 0),
    'leitores_ativos', count(distinct p.usuario_id)
      filter (where p.data_leitura >= current_date - 6 and p.paginas_lidas > 0),
    'atividade_anonima', coalesce((
      select jsonb_agg(
        jsonb_build_object('data', atividade.dia, 'paginas', atividade.paginas)
        order by atividade.dia desc
      )
      from (
        select p2.data_leitura as dia, sum(p2.paginas_lidas) as paginas
        from public.progresso_leitura p2
        where p2.encontro_id = p_encontro_id
          and p2.data_leitura between current_date - 13 and current_date
          and p2.paginas_lidas > 0
        group by p2.data_leitura
        having count(distinct p2.usuario_id) >= 3
        order by p2.data_leitura desc
        limit 14
      ) atividade
    ), '[]'::jsonb)
  )
  into resultado
  from public.progresso_leitura p
  where p.encontro_id = p_encontro_id
    and p.data_leitura <= current_date;

  select jsonb_build_object(
    'participantes_com_edicao', count(edicao.usuario_id),
    'participantes_com_progresso', count(edicao.usuario_id)
      filter (where leitura.total_paginas > 0),
    'paginas_medias_por_membro', coalesce(
      round(avg(least(coalesce(leitura.total_paginas, 0), edicao.paginas_totais)), 1),
      0
    ),
    'progresso_medio_percentual', coalesce(
      round(avg(
        100.0 * least(coalesce(leitura.total_paginas, 0), edicao.paginas_totais)
          / nullif(edicao.paginas_totais, 0)
      ), 1),
      0
    ),
    'progresso_por_edicao', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'edicao', grupo.edicao,
          'paginas_totais', grupo.paginas_totais,
          'participantes', grupo.participantes,
          'total_paginas', grupo.total_paginas,
          'progresso_medio_percentual', grupo.progresso_medio_percentual
        )
        order by grupo.edicao, grupo.paginas_totais
      )
      from (
        select
          min(btrim(ed.edicao)) as edicao,
          ed.paginas_totais,
          count(*) as participantes,
          sum(coalesce(leitura_edicao.total_paginas, 0)) as total_paginas,
          round(avg(
            100.0 * least(coalesce(leitura_edicao.total_paginas, 0), ed.paginas_totais)
              / ed.paginas_totais
          ), 1) as progresso_medio_percentual
        from public.edicoes_leitura ed
        left join lateral (
          select coalesce(sum(p.paginas_lidas), 0)::numeric as total_paginas
          from public.progresso_leitura p
          where p.usuario_id = ed.usuario_id
            and p.encontro_id = ed.encontro_id
            and p.data_leitura <= current_date
        ) leitura_edicao on true
        where ed.encontro_id = p_encontro_id
        group by lower(btrim(ed.edicao)), ed.paginas_totais
      ) grupo
    ), '[]'::jsonb)
  )
  into progresso_coletivo
  from public.edicoes_leitura edicao
  left join lateral (
    select coalesce(sum(p.paginas_lidas), 0)::numeric as total_paginas
    from public.progresso_leitura p
    where p.usuario_id = edicao.usuario_id
      and p.encontro_id = edicao.encontro_id
      and p.data_leitura <= current_date
  ) leitura on true
  where edicao.encontro_id = p_encontro_id;

  return resultado || progresso_coletivo;
end;
$$;

create or replace function public.clube_cartoes_progresso_publicos(p_encontro_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id_publico', compartilhado.id_publico,
        'eh_meu', compartilhado.usuario_id = auth.uid(),
        'mostrar_nome', compartilhado.mostrar_nome
          and detalhes.visibilidade_nome = 'publico',
        'mostrar_foto', compartilhado.mostrar_foto
          and detalhes.visibilidade_foto = 'publico',
        'nome', case
          when compartilhado.mostrar_nome
            and detalhes.visibilidade_nome = 'publico'
          then coalesce(perfil.nome, 'Leitor(a)')
          else null
        end,
        'foto_url', case
          when compartilhado.mostrar_foto
            and detalhes.visibilidade_foto = 'publico'
          then coalesce(perfil.foto_url, '')
          else ''
        end,
        'paginas_lidas', progresso.total_paginas,
        'edicao', coalesce(edicao.edicao, ''),
        'paginas_totais', coalesce(edicao.paginas_totais, encontro.paginas_totais),
        'titulo', encontro.titulo,
        'autor', encontro.autor,
        'capa', encontro.capa
      )
      order by compartilhado.publicado_em desc
    ),
    '[]'::jsonb
  )
  from public.encontros encontro
  join public.progresso_leitura_compartilhado compartilhado
    on compartilhado.encontro_id = encontro.id
  left join public.perfis_clube perfil
    on perfil.id = compartilhado.usuario_id
  left join public.perfis_clube_detalhes detalhes
    on detalhes.usuario_id = compartilhado.usuario_id
  left join public.edicoes_leitura edicao
    on edicao.usuario_id = compartilhado.usuario_id
    and edicao.encontro_id = compartilhado.encontro_id
  join lateral (
    select coalesce(sum(p.paginas_lidas), 0) as total_paginas
    from public.progresso_leitura p
    where p.usuario_id = compartilhado.usuario_id
      and p.encontro_id = compartilhado.encontro_id
      and p.data_leitura <= current_date
  ) progresso on true
  where encontro.id = p_encontro_id
    and encontro.status = 'atual'
    and coalesce(encontro.tipo_postagem, 'clube') = 'clube'
    and progresso.total_paginas > 0;
$$;

